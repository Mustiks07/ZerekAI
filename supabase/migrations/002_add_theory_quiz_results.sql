-- ─── Шаг 1: Расширяем существующие таблицы ───────────────────────────

ALTER TABLE topics
  ADD COLUMN IF NOT EXISTS theory_text TEXT NOT NULL DEFAULT '';

ALTER TABLE questions
  ADD COLUMN IF NOT EXISTS explanation TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS subject_id  UUID REFERENCES subjects(id) ON DELETE CASCADE;

-- Заполняем subject_id у уже существующих вопросов
UPDATE questions q
   SET subject_id = t.subject_id
  FROM topics t
 WHERE q.topic_id = t.id
   AND q.subject_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_questions_subject_active
    ON questions(subject_id, is_active);

-- ─── Шаг 2: Таблица quiz_results ─────────────────────────────────────

CREATE TABLE IF NOT EXISTS quiz_results (
  id              UUID        PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id         UUID        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  topic_id        UUID        NOT NULL REFERENCES topics(id)     ON DELETE CASCADE,
  subject_id      UUID        REFERENCES subjects(id),
  score           INTEGER     NOT NULL DEFAULT 0,
  total_questions INTEGER     NOT NULL DEFAULT 0,
  time_spent      INTEGER     NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE quiz_results ENABLE ROW LEVEL SECURITY;

CREATE POLICY IF NOT EXISTS "quiz_results select own"
  ON quiz_results FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY IF NOT EXISTS "quiz_results insert own"
  ON quiz_results FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_quiz_results_user
    ON quiz_results(user_id, created_at DESC);

